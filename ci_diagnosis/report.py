"""Validate the model's answer and render it as safe markdown."""

import json
import re
from typing import Literal

from pydantic import BaseModel, Field, ValidationError

# Hidden marker that identifies our PR comment, so it is updated, not duplicated.
COMMENT_MARKER = "<!-- ci-ai-diagnosis -->"


class Diagnosis(BaseModel):
    failed_stage: str = Field(max_length=100)
    root_cause: str = Field(max_length=1500)
    suggested_fix: str = Field(max_length=2000)
    confidence: Literal["high", "medium", "low"]
    evidence: list[str] = Field(default_factory=list, max_length=5)


class InvalidDiagnosis(Exception):
    """The model's answer was not valid JSON matching Diagnosis."""


def parse_diagnosis(raw: str) -> Diagnosis:
    # Some models wrap JSON in a ```json fence despite instructions.
    cleaned = re.sub(r"^\s*```(?:json)?\s*|\s*```\s*$", "", raw.strip())
    try:
        return Diagnosis.model_validate(json.loads(cleaned))
    except (json.JSONDecodeError, ValidationError) as exc:
        raise InvalidDiagnosis(str(exc)) from exc


def sanitize(text: str) -> str:
    """Neutralize model output before it is rendered as markdown on GitHub.

    The model read untrusted logs, so its text is untrusted too:
    - HTML is escaped (no <img> or other tags that load URLs, no <autolinks>).
    - Images are removed, inline and reference-style: GitHub fetches an image
      when the page renders, so its URL could leak data.
    - Links keep only their text; reference definitions are dropped.
    - Bare URLs are defanged (https[:]//, www[.]) so they are not clickable.
    - @mentions get a zero-width space so nobody is notified.
    """
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    # Reference definitions: "[id]: https://..." on their own line
    text = re.sub(r"(?m)^[ \t]*\[[^\]]+\]:[ \t]*\S.*$", "", text)
    # Images and links, inline "(url)" or reference "[id]" style
    text = re.sub(r"!\[([^\]]*)\](?:\([^)]*\)|\[[^\]]*\])", r"\1", text)
    text = re.sub(r"\[([^\]]*)\](?:\([^)]*\)|\[[^\]]*\])", r"\1", text)
    # Bare URLs that GitHub would autolink
    text = text.replace("://", "[:]//")
    text = re.sub(r"(?i)\bwww\.", "www[.]", text)
    text = re.sub(r"@(?=[A-Za-z0-9])", "@​", text)
    return text.strip()


def _code_block(lines: list[str]) -> str:
    """A fenced block whose fence is longer than any backtick run inside it,
    so the content cannot close the block early."""
    body = "\n".join(lines)
    longest = max((len(m) for m in re.findall(r"`+", body)), default=0)
    fence = "`" * max(3, longest + 1)
    return f"{fence}text\n{body}\n{fence}"


def render_diagnosis(diag: Diagnosis, failed_jobs: list[str], run_url: str) -> str:
    parts = [
        COMMENT_MARKER,
        "## 🤖 CI failure diagnosis",
        "",
        f"**Failed jobs:** {sanitize(', '.join(failed_jobs))}",
        f"**Stage:** {sanitize(diag.failed_stage)}",
        f"**Confidence:** {diag.confidence}",
        "",
        "### Root cause",
        sanitize(diag.root_cause),
        "",
        "### Suggested fix",
        sanitize(diag.suggested_fix),
    ]
    if diag.evidence:
        parts += ["", "### Evidence from the logs", _code_block(diag.evidence)]
    parts += [
        "",
        f"[View the failed run]({run_url})",
        "",
        "<sub>Generated by a language model from the job logs. "
        "Verify before acting on it.</sub>",
    ]
    return "\n".join(parts)


def render_fallback(failed_jobs: list[str], run_url: str, reason: str) -> str:
    """Plain failure notice when the model is unavailable or its answer invalid."""
    jobs = "\n".join(f"- {sanitize(name)}" for name in failed_jobs) or "- (unknown)"
    return "\n".join(
        [
            COMMENT_MARKER,
            "## ❌ CI failed",
            "",
            "**Failed jobs:**",
            jobs,
            "",
            f"AI diagnosis unavailable: {sanitize(reason)}",
            "",
            f"[View the failed run]({run_url})",
        ]
    )
